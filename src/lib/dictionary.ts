// Dedupe and clamp to 3–7 letters: longer words can't fit a 7-letter rack, and
// the unique set keeps Anagram yields and the Ladder graph clean.
export const ALL_WORDS: string[] = [...new Set(RAW_WORDS.filter((w) => w.length >= 3 && w.length <= 7))]

export const LADDER_WORDS: string[] = [...new Set(ALL_WORDS.filter((w) => w.length === 4))]

export const WORD_SET: Set<string> = new Set(ALL_WORDS)

export function isWord(w: string): boolean {
  return WORD_SET.has(w.toLowerCase())
}

export function wordDistance(a: string, b: string): number {
  if (a.length !== b.length) return 99
  let d = 0
  for (let i = 0; i < a.length; i++) {
    if (a[i] !== b[i]) d++
  }
  return d
}

function buildLadderAdjacency(): Map<string, string[]> {
  const m = new Map<string, string[]>()
  for (const w of LADDER_WORDS) {
    const n = LADDER_WORDS.filter((o) => wordDistance(w, o) === 1)
    m.set(w, n)
  }
  return m
}

const LADDER_ADJ = buildLadderAdjacency()

export function ladderNeighbors(word: string): string[] {
  return LADDER_ADJ.get(word) ?? []
}

// Pick a reachable target word at a given BFS depth range, or null.
export function findLadderTarget(start: string, minDepth: number, maxDepth: number): string | null {
  const seen = new Set<string>([start])
  let frontier = [start]
  let depth = 0
  const candidates: string[] = []
  while (frontier.length > 0 && depth < maxDepth) {
    depth++
    const next: string[] = []
    for (const w of frontier) {
      for (const n of LADDER_ADJ.get(w) ?? []) {
        if (seen.has(n)) continue
        seen.add(n)
        if (depth >= minDepth) candidates.push(n)
        next.push(n)
      }
    }
    frontier = next
  }
  if (candidates.length === 0) return null
  return candidates[Math.floor(Math.random() * candidates.length)]
}

function letterCounts(word: string): Map<string, number> {
  const m = new Map<string, number>()
  for (const ch of word) m.set(ch, (m.get(ch) ?? 0) + 1)
  return m
}

function canSpell(word: string, rack: Map<string, number>): boolean {
  const needed = letterCounts(word)
  for (const [ch, n] of needed) {
    if ((rack.get(ch) ?? 0) < n) return false
  }
  return true
}

// All dictionary words (3+ letters) that fit inside the given rack letters.
export function wordsFromRack(rack: string[]): string[] {
  const counts = letterCounts(rack.join(''))
  return [...WORD_SET].filter((w) => canSpell(w, counts))
}
